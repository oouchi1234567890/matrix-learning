const angleLabels = [
  "", "の要点", "の定義", "の仕組み", "の目的", "の特徴", "の利点",
  "の注意点", "の試験対策", "の基礎", "の活用", "の確認",
  "の関連知識", "の重要事項", "の実務",
];

function expandTopics(topics, angleCount) {
  return topics.flatMap(([term, meaning]) =>
    angleLabels
      .slice(0, angleCount)
      .map((angle) => `${term}${angle}：${meaning}`),
  );
}

const knowledgeCategories = {
  ai: expandTopics(additionalTopics.slice(0, 50), 14),
  applied: expandTopics(additionalTopics.slice(50, 100), 12),
  security: expandTopics(securityTopics, 15),
  infrastructure: expandTopics(infrastructureTopics, 10),
  governance: expandTopics(governanceTopics, 10),
};

const knowledgeTerms = Object.values(knowledgeCategories).flat();

const expectedCounts = {
  ai: 700,
  applied: 600,
  security: 300,
  infrastructure: 250,
  governance: 150,
};

for (const [category, expected] of Object.entries(expectedCounts)) {
  if (knowledgeCategories[category].length !== expected) {
    throw new Error(`${category} must contain ${expected} terms`);
  }
}
if (knowledgeTerms.length !== 2000 || new Set(knowledgeTerms).size !== 2000) {
  throw new Error("Knowledge terms must contain exactly 2,000 unique items");
}
